const heFilePath = path.join(__dirname, "..", "src", "locale", "he.json");

try {
  const he = JSON.parse(fs.readFileSync(heFilePath, "utf-8"));

  // Update holyNames with Hebrew translations
  if (!he.holyNames) {
    he.holyNames = {};
  }

  for (let i = 0; i < hebrewData.length; i++) {
    he.holyNames[i + 1] = {
      transliteration: hebrewData[i][0],
      meaning: hebrewData[i][1],
    };
  }

  // Also update page title and subtitle if they exist
  if (he.pages && he.pages.holynames) {
    he.pages.holynames.title = "99 שמות הקודש של אללה";
    he.pages.holynames.subtitle = "שמות הקודש";
  }

  fs.writeFileSync(heFilePath, JSON.stringify(he, null, 2), "utf-8");
  console.log("✅ Hebrew translations added successfully to he.json");
} catch (error) {
  console.error("❌ Error updating he.json:", error);
  process.exit(1);
}
